"""
Tests for topagnps2cche1d.network (CCHE1D network builder / writer /
validator / reader).

These tests load ``network.py`` directly so they run without the package's
heavy TopAGNPS dependencies (GDAL, pandas, holoviews); network.py itself is
stdlib-only.  Inside the pixi environment they pass either way.

# Run:  pixi run test        (or: pytest -q tests)

validate_network() returns ``(errors, warnings)``: a non-empty error list
raises NetworkValidationError, a warnings-only result is "imports cleanly,
geometry may be incomplete" (the Fortran import tolerates those cases).
"""

import importlib.util
import sys
from pathlib import Path

# Run under real pytest (pixi feature `test`) or with a tiny fallback shim so
# the suite also works on a bare interpreter:  python3 tests/test_network.py
try:
    import pytest
except ModuleNotFoundError:  # pragma: no cover - bare interpreter fallback
    class _Raises:
        def __init__(self, exc, match=None):
            self.exc, self.match = exc, match
            self.value = None
        def __enter__(self):
            return self
        def __exit__(self, et, ev, tb):
            if et is None:
                raise AssertionError(f"{self.exc} not raised")
            if not issubclass(et, self.exc):
                return False
            if self.match and not (self.match in str(ev)):
                raise AssertionError(f"{self.match!r} not in {ev}")
            self.value = ev
            return True
    class _PytestShim:
        @staticmethod
        def raises(exc, match=None):
            return _Raises(exc, match)
    pytest = _PytestShim()

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location(
    "topagnps2cche1d_network", ROOT / "topagnps2cche1d" / "network.py")
net = importlib.util.module_from_spec(SPEC)
sys.modules["topagnps2cche1d_network"] = net
SPEC.loader.exec_module(net)

GT_DIR = ROOT / "data_inputs" / "netchanTest_example_cche1d_input_files"
LOOPTEST_DIR = ROOT / "documents" / "LoopTest"


def simple_network():
    """1 outlet channel + 2 inflows merging at its head."""
    return {
        1: (None, [(0, 0), (5, 0), (10, 0)]),          # outlet
        2: (1, [(20, -20), (15, -10), (10, 0)]),       # left inflow
        3: (1, [(20, 20), (15, 10), (10, 0)]),         # right inflow
    }


