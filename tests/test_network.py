def test_builder_two_inflow_junction():
    n = net.ChannelNetworkBuilder(
        simple_network(), resample_step=4, cs_template=(2, 2, 2, 2)).build()
    assert len(n.channels) == 3
    junc = [x for x in n.nodes if x.nd_type == net.NODE_JUNCTION]
    assert len(junc) == 1
    j = junc[0]
    assert j.usid != -1 and j.us2id != -1
    # both branches discharge into the junction
    for b in (j.usid, j.us2id):
        assert n.node_by_id(b).dsid == j.nd_id
    assert net.validate_network(n) == ([], [])


def test_builder_three_way_junction():
    ch = {
        1: (None, [(0, 0), (10, 0)]),
        2: (1, [(30, -30), (10, 0)]),
        3: (1, [(30, 0), (10, 0)]),
        4: (1, [(30, 30), (10, 0)]),
    }
    n = net.ChannelNetworkBuilder(ch, resample_step=8).build()
    j = [x for x in n.nodes if x.nd_type == net.NODE_JUNCTION][0]
    assert len(n.junction_branches(j.nd_id)) == 3
    # the third branch is stored in the junction block, not inline
    extra = [x for x in n.junctions if x.node_id == j.nd_id][0]
    assert extra.branches345[0] != -1
    assert net.validate_network(n) == ([], [])


def test_builder_rejects_more_than_five_inflows():
    ch = {1: (None, [(0, 0), (10, 0)])}
    for i in range(2, 8):
        ch[i] = (1, [(30, -40 + 16 * (i - 2)), (10, 0)])
    with pytest.raises(ValueError, match="at most 5"):
        net.ChannelNetworkBuilder(ch).build()


def test_builder_rejects_missing_outlet():
    with pytest.raises(ValueError, match="outlet"):
        net.ChannelNetworkBuilder({1: (2, [(0, 0), (1, 0)]),
                                  2: (1, [(1, 1), (0, 0)])}).build()


def test_write_read_round_trip_symmetric():
    n = net.ChannelNetworkBuilder(simple_network(),
                                  resample_step=4).build()
    out = Path(__file__).parent / "_rt"
    out.mkdir(exist_ok=True)
    net.write_cche1d_dat_files(n, out, prefix="t")
    r = net.read_cche1d_network(out)
    assert len(r.nodes) == len(n.nodes)
    assert [(j.node_id, j.branches345) for j in r.junctions] == \
           [(j.node_id, j.branches345) for j in n.junctions]
    assert net.validate_network(r) == ([], [])


def test_builder_accepts_generic_reach_objects():
    # Duck-typed stand-ins for topagnps2cche1d.Reach / .Node so this test
    # also runs in a bare interpreter (the pixi env exercises the REAL
    # classes in tests/_check_reach_adapter.py, run via `pixi run test2`).
    class RNode:
        def __init__(self, x, y, dsid=None):
            self.x, self.y, self.dsid = x, y, dsid

    class RReach:
        def __init__(self, id, receiving_reach_id, pts):
            self.id = id
            self.receiving_reach_id = receiving_reach_id
            self.nodes = {}
            prev = None
            for i, (x, y) in enumerate(pts):
                nid = 100 * id + i
                self.nodes[nid] = RNode(x, y,
                                        dsid=100 * id + i + 1 if i + 1 < len(pts)
                                        else None)
                if prev is not None:
                    prev.dsid = nid
                prev = self.nodes[nid]
            self.us_nd_id = 100 * id
            self.ds_nd_id = 100 * id + len(pts) - 1

    spec = simple_network()
    reaches = [RReach(r, spec[r][0], spec[r][1]) for r in spec]
    n = net.ChannelNetworkBuilder(reaches, resample_step=4).build()
    assert len(n.channels) == 3
    assert net.validate_network(n) == ([], [])


def test_channel_defs_from_reaches_accepts_single_node_reach():
    # A single-node reach is legal: it becomes a 1-point channel (head == tail).
    class RNode:
        def __init__(self, x, y, dsid=None):
            self.x, self.y, self.dsid = x, y, dsid
            self.id = None

    node = RNode(10.0, 20.0)
    node.id = 5

    class RReach:
        id = 1
        receiving_reach_id = None
        nodes = {5: node}
        us_nd_id = 5
        ds_nd_id = 5

    defs = net.channel_defs_from_reaches([RReach()])
    assert defs[1] == (None, [(10.0, 20.0)])


def test_channel_defs_from_reaches_rejects_reach_with_no_us_node():
    class RReach:
        id = 1
        receiving_reach_id = None
        nodes = {}
        us_nd_id = 5

    with pytest.raises(KeyError):
        net.channel_defs_from_reaches([RReach()])


def test_one_point_channel_builds_and_validates():
    # A 1-point channel (head == tail) is a legal CCHE1D construct: it comes
    # from an unexpanded boundary single-node reach after coarsening.  Its
    # link carries the -1 reach-range sentinel and the validator accepts it.
    spec = {
        1: (None, [(0, 0)]),                # outlet: 1 point
        2: (1, [(10, 5), (5, 0)]),          # 2-point inflow
        3: (1, [(10, -5), (5, 0)]),         # 2-point inflow (junction head)
    }
    n = net.ChannelNetworkBuilder(spec).build()
    assert len(n.channels) == 3
    # channel 1 (the 1-point one) has no reach rows
    onepoint = [c for c in n.channels if c.ndusid == c.nddsid]
    assert len(onepoint) == 1
    sent = [l for l in n.links if l.rcusid == net.NEGATIVE_ONE]
    assert len(sent) == 1 and sent[0].rcdsid == net.NEGATIVE_ONE
    assert net.validate_network(n) == ([], [])
    # round-trip through the writer/reader keeps the sentinel
    import tempfile
    with tempfile.TemporaryDirectory() as d:
        net.write_cche1d_dat_files(n, d, prefix="oncpt")
        n2 = net.read_cche1d_network(d)
        assert net.validate_network(n2) == ([], [])
        assert any(l.rcusid == net.NEGATIVE_ONE for l in n2.links)



